def lookup_port(port: int) -> tuple:
    """
    Returns (service_name, proto_tag, description, category) for a given port.
    Falls back to UNKNOWN if not in DB.
    """
    if port in PORT_DB:
        return PORT_DB[port]
    # Range-based fallbacks
    if 0 <= port <= 1023:
        return (f"SYSTEM-{port}", "SYS", f"System port {port}", "STANDARD")
    if 1024 <= port <= 49151:
        return (f"REG-{port}", "REG", f"Registered port {port}", "STANDARD")
    # Ephemeral / dynamic
    return (f"EPHEMERAL-{port}", "EPH", f"Dynamic/ephemeral port {port}", "STANDARD")


def get_top_protocol(src_port: int, dst_port: int) -> str:
    """Determine the application-layer protocol from port pair."""
    # Check destination first (server port), then source
    for port in (dst_port, src_port):
        entry = PORT_DB.get(port)
        if entry:
            return entry[0]  # service name
    return f"PORT-{dst_port}"


def is_risky_port(port: int) -> bool:
    entry = PORT_DB.get(port)
    if entry:
        return entry[3] in ("RISKY", "MALWARE", "C2")
    return False


def get_category(port: int) -> str:
    return PORT_DB.get(port, ("", "", "", "STANDARD"))[3]
