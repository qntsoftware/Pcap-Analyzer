def set_lang(lang_code: str):
    """Dil kodunu ayarla (alias desteği ile)."""
    global _CURRENT_LANG
    code = LANG_ALIASES.get(lang_code.lower().strip(), None)
    if code is None:
        print(f"\033[93m[LANG] '{lang_code}' desteklenmiyor. Varsayılan: English\033[0m")
        code = "eng"
    _CURRENT_LANG = code
    os.environ["PCAP_LANG"] = code


def get_lang() -> str:
    return os.environ.get("PCAP_LANG", _CURRENT_LANG)


def L(key: str, **fmt) -> str:
    """
    Çeviri sözlüğünden metin al.
    L("analyzing") → "Analyzing..." / "Analiz ediliyor..." / "Analysiere..."
    """
    lang = get_lang()
    text = TRANSLATIONS.get(key, {}).get(lang) \
        or TRANSLATIONS.get(key, {}).get("eng") \
        or key
    if fmt:
        try:
            text = text.format(**fmt)
        except KeyError:
            pass
    return text


def get_ai_language_instruction() -> str:
    """AI prompt'una eklenmek üzere dil talimatı döndür."""
    lang = get_lang()
    name = LANG_NAMES.get(lang, "English")
    if lang == "eng":
        return "Respond entirely in English."
    return (
        f"IMPORTANT: You MUST respond entirely in {name}. "
        f"All analysis, summaries, findings, recommendations, "
        f"packet explanations, and all text in the JSON response "
        f"must be written in {name}. Do NOT use any other language."
    )


